/// 规则文件后缀：`<rules_dir>/<name>.rules`。
pub const RULES_SUFFIX: &str = ".rules";

/// 规则名 → 文件名。**只接受白名单名字**（校验见 `domain` 的
/// `validate_rules_name`），这里再拼后缀，绝不接受调用方给的路径片段。
pub fn file_name_for(name: &str) -> String {
    format!("{name}{RULES_SUFFIX}")
}
