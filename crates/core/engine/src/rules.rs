//! envboard 的 hosts 规则解析与确定性渲染 —— **本模块文档即规则语法契约（BNF）**。
//! golden fixture（`tests/contract-tests/fixtures/rules/`）的期望正文由本实现
//! 重算，契约测试逐例消费。纯逻辑：不碰文件系统、不碰网络（原子落盘与 0600
//! 权限由 manager 负责）。
//!
//! 规则文件的使命：把**人手写的、杂乱的 hosts 风格输入**规范成一份**确定性**
//! 的静态覆盖表（`host → ip`），在建连时用于改写上连目标地址。
//!
//! ## 1. 词法与行结构
//!
//! ```bnf
//! file          = [ bom ] , { line } ;
//! bom           = "\uFEFF" , { "\uFEFF" } ;        (* 行首的全部 BOM 一并剥掉 *)
//! line          = { ws } , [ body , { ws } , [ comment ] ] , { ws } , [ eol ] ;
//! comment       = "#" , { any-char } ;              (* 行内首个 # 之后全部丢弃 *)
//! body          = { ws } , token , { ws1 , token } , { ws } ;
//! token         = ip | host-token ;
//! host-token    = { any-char - ( ws | "#" ) } ;
//! ws            = " " | "\t" | { unicode-white-space } ;
//! ws1           = ws , { ws } ;                     (* 至少一个空白字符 *)
//! eol           = "\n" | "\r\n" | "\r" ;
//! ```
//!
//! 行分隔只承认 `\n`、`\r\n`、`\r` 三种。注释截断发生在**原始行**上、取第一个
//! `#`（域名里不能含 `#`）。行分类按处理顺序取第一个匹配：strip 后以 `#` 开头
//! → 注释行（comment_lines）；截断后 body 为空且不是注释行 → 空行
//! （blank_lines）；body 非空 → 数据行（data_lines）。区分依据是**原文** strip
//! 后是否以 `#` 开头：`   ` 是空行，`   # x` 是注释行，
//! `10.0.0.1 a.example.com   # 行尾注释` 是数据行。
//!
//! ## 2. 语法
//!
//! ```bnf
//! entry         = ip-first | host-last ;
//! ip-first      = ip , ws1 , host , { ws1 , host } ;
//! host-last     = host , ws1 , { host , ws1 } , ip ;
//! ip            = ipv4 | ipv6 | "[" , ipv6 , "]" ;
//! ```
//!
//! 判定顺序（只看 token）：`tokens[0]` 是 IP 字面量 → ip-first；否则 `tokens[-1]`
//! 是 IP 字面量 → host-last；否则整行跳过（`no-ip-literal`）。两种写法等价：
//! `10.0.0.1 a.example.com` 与 `a.example.com 10.0.0.1` 产出同一条映射。
//!
//! ## 3. 归一化
//!
//! **host**：strip → 转小写 → 去尾部所有根点；若以 `*.` 开头剥掉这一个前缀
//! （只剥一次、仅限开头）；结果非空且 ≤253；按 `.` 切分后每个 label 匹配
//! `^(?!-)[A-Za-z0-9_-]{1,63}(?<!-)$`（允许 `_`，不能以 `-` 开头/结尾，空 label
//! 不合法）。**不支持通配符匹配**：`*.wild.example.com` 只是归一化成
//! `wild.example.com`，语义是"这一个域名"。
//!
//! **ip**：strip；首尾同时是 `[` `]` 则剥掉这一对；必须能被标准 IP 字面量
//! 解析器解析（`IpAddr::from_str`）。拒绝：`ip:port`、主机名、前导零 IPv4
//! （`010.0.0.1`）、越界八位组、**带 zone id 的 IPv6**（`fe80::1%eth0`）。
//! **IP 文本不做规范化 —— 拼法保留**：`2001:0db8::1` 不改写成 `2001:db8::1`。
//! 理由：渲染出的文件要能被重新导入且不产生 diff（改写拼法像"工具乱改我的
//! 东西"）。排序仍按 IP **数值**序，拼法不影响次序。
//!
//! ## 4. 逐项容错与跳过原因码
//!
//! **非法内容永远不会让整次导入失败**，但每一处忽略都必须如实记录
//! （行号 + 原因码 + 原文片段），不允许静默吞掉。
//!
//! | 原因码 | 触发 | detail | 影响范围 |
//! |---|---|---|---|
//! | `too-few-tokens` | 数据行 token 数 < 2 | 第一个 token | 整行 |
//! | `no-ip-literal` | 首尾 token 都不是 IP 字面量 | `""` | 整行 |
//! | `invalid-host` | host 位置的 token 不合法，或本身是 IP 字面量 | 该 token | **只丢该项**，同行其余 host 保留 |
//!
//! 原因码是稳定字面量（UI 与 fixture 按它断言）。`10.0.0.7 10.0.0.8` 的第二个
//! IP 记 invalid-host；同一行可产出多条 invalid-host（按 token 出现顺序）。
//!
//! ## 5. 冲突
//!
//! 同一 host 映射到**不同** ip → **后出现者胜**，记一条冲突
//! `[host, dropped, kept]`；映射到相同 ip → 不记冲突。判等按 IP **文本**
//! （拼法保留）：`2001:db8::1` 与 `2001:0db8::1` 是两次不同映射，记冲突。
//!
//! ## 6. 渲染（持久化格式）
//!
//! 渲染必须**确定性**：同一份 entries + source 逐字节相同；
//! `parse(render(x)) == parse(x)`，重复导入不产生 diff。
//!
//! ```bnf
//! rendered      = header , [ source-line ] , counts-line , blank , { entry-line } ;
//! header        = "# envboard rules file — normalized `ip host...` lines.\n"
//!               , "# Generated by envboard; re-import the source instead of editing this by hand.\n" ;
//! source-line   = "# source: " , source-text , "\n" ;          (* 仅当 source 非空 *)
//! counts-line   = "# entries: " , N , "  " , "ip: " , M , "\n" ; (* 两个空格 *)
//! blank         = "\n" ;
//! entry-line    = ip , " " , host , { " " , host } , "\n" ;
//! ```
//!
//! 首两行是固定字节（含 U+2014 破折号、反引号与结尾句点），改一个字就是
//! breaking change。N = 归一化后 host 数，M = 去重后 ip 数。计数行后恰好一个
//! 空行。数据行每个 ip 一行，ip 按**数值序**（先地址族：IPv4 全部在 IPv6 前，
//! 同族按地址字节序）；行内 host 按 **Unicode 码点序**；文件以恰好一个 `\n`
//! 结尾。渲染前 entries 必须已归一化；**两个键归一化后撞车（`A.com` 与
//! `a.com`）必须 `invalid_config` 响亮失败**，不得依赖迭代顺序静默取一个。
//!
//! ## 7. 结果载荷（契约测试可比对的字段）
//!
//! `entries`（{归一化 host: ip 文本}，后出现者胜）、`accepted`（条目数）、
//! `ips`（去重 ip 数）、`conflicts`（[[host, dropped, kept]…] 按发生顺序）、
//! `skipped`（{line, text, reason, detail}；line 从 1 起，text 是截断注释并
//! strip 后的 body）、`stats`（{total_lines, blank_lines, comment_lines,
//! data_lines, accepted, skipped, conflicts}，后两者是条数）。
//! `blank_lines + comment_lines + data_lines == total_lines`。
//!
//! ## 8. 生效语义（解析之外，但同属契约）
//!
//! 规则在**建连时**改写上连目标地址：只改"往哪连"，不改请求内容、不改 Host
//! 头、不改 SNI 基准。只对**请求里给出了域名**的上连生效（客户端直连 IP 无
//! 域名可匹配）；只对**流量指向了该环境端口**的请求生效（不改系统 DNS、
//! 不全机生效）。已知代价：改写后的地址与请求 host 不相等，上游连接池因此
//! 不再复用该 host 的连接，每请求新建上连（正确性不受影响）。
//!
//! ## insecure_hosts / mitm_hosts 的域名判定
//!
//! 两个清单共用本模块的归一化与**精确相等**命中判定（[`insecure`] 子模块）：
//! 无通配符、无子域继承、无后缀匹配；写入时拒绝 `*` / `?`（不做规则文件那套
//! 剥 `*.` 前缀的处理 —— 那会让"没生效"变成"生效范围比你以为的大"）。
//! 区别只在方向：`insecure_hosts` 命中 = 放宽上游证书校验（SNI 优先，无 SNI
//! 才退回上连地址，SNI 存在未命中**不**退回）；`mitm_hosts` 命中 = 解密
//! （空 = 全部解密；判定在 CONNECT authority 上，名单外直通盲隧道）。

